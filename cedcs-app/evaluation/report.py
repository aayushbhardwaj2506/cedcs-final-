"""Turns the experiment results into paper-ready Markdown tables, CSV files and figures. No numbers are typed in here."""

from __future__ import annotations

import csv
import math
from pathlib import Path

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

OKABE = {"B1": "#999999", "B2": "#E69F00", "B3": "#56B4E9", "B4": "#009E73", "CEDCS": "#0072B2", "oracle": "#CC79A7", "B5": "#D55E00"}
SHORT = {"B1 nearest": "B1", "B2 nearest with ED": "B2", "B3 distance + specialty": "B3", "B4 soft ranking, no gate, no freshness": "B4", "CEDCS": "CEDCS", "oracle": "oracle"}


def pct(x, d=1):
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{100 * x:.{d}f}%"


def pci(x, ci, d=1):
    return "n/a" if x is None or math.isnan(x) else f"{100 * x:.{d}f}% [{100 * ci[0]:.{d}f}, {100 * ci[1]:.{d}f}]"


def num(x, d=2):
    return "n/a" if x is None or (isinstance(x, float) and math.isnan(x)) else f"{x:.{d}f}"


def mci(t, d=2):
    return "n/a" if t is None or math.isnan(t[0]) else f"{t[0]:.{d}f} [{t[1]:.{d}f}, {t[2]:.{d}f}]"


def pval(p):
    return "<0.001" if p < 0.001 else f"{p:.3f}"


def table(header: list, rows: list) -> str:
    return "\n".join(["| " + " | ".join(header) + " |", "|" + "|".join("---" for _ in header) + "|"] + ["| " + " | ".join(str(c) for c in r) + " |" for r in rows])


def write_csv(path: Path, header: list, rows: list) -> None:
    with open(path, "w", newline="", encoding="utf-8") as f:
        w = csv.writer(f)
        w.writerow(header)
        w.writerows(rows)


def _style(ax, title, ylabel):
    ax.set_title(title, fontsize=11, loc="left")
    ax.set_ylabel(ylabel)
    ax.grid(axis="y", alpha=0.25)
    for s in ("top", "right"):
        ax.spines[s].set_visible(False)


def build(res: dict, out: Path, config: dict) -> str:
    out.mkdir(parents=True, exist_ok=True)
    fig_dir = out / "figures"
    fig_dir.mkdir(exist_ok=True)
    md = [f"# CEDCS evaluation results\n\nGenerated by `python -m evaluation.run` (seed {config['seed']}). {config['worlds']} synthetic worlds x {config['cases']} cases = "
          f"{config['worlds'] * config['cases']} cases per condition; hospitals per world: {config['hospitals']}. Every number below is computed by the code in "
          "`evaluation/`; intervals are 95 % (Wilson for proportions, bootstrap for means). All results are about a SIMULATION with the assumptions in METHODS.md.\n"]

    # ------------------------------------------------------------ E1
    e1 = res["e1"]
    for load, d in e1.items():
        rows, csvrows = [], []
        for name, s in d["summary"].items():
            if name == "oracle":
                continue
            p = d["mcnemar_p_vs_cedcs"].get(name)
            r = [SHORT[name], pct(s["handoff_rate"]), pci(s["undertriage"], s["undertriage_ci"]), pci(s["undertriage_avoidable"], s["undertriage_avoidable_ci"]),
                 f"{s['violations']} ({pct(s['violation_rate'])})", pct(s["overtriage"]), num(s["req_coverage"][0], 3), mci(s["excess_min"], 1), mci(s["cost"], 2), "-" if p is None else pval(p)]
            rows.append(r)
            csvrows.append([load, SHORT[name]] + [s["n"], s["issued"], s["handoff_rate"], s["undertriage"], s["undertriage_avoidable"], s["violations"], s["overtriage"],
                                                 s["req_coverage"][0], s["excess_min"][0], s["cost"][0], s["ms_mean"], p])
        hdr = ["Policy", "Handoff", "Undertriage (issued)", "Undertriage (avoidable cases)", "Safety violations", "Overtriage", "Required-capability coverage",
               "Excess ETA (min)", "Cost-weighted error", "p vs CEDCS (McNemar)"]
        md.append(f"## E1. Main comparison, city load: {load}\n\n" + table(hdr, rows) + "\n")
        write_csv(out / f"e1_main_{load}.csv", ["load", "policy", "n", "issued", "handoff_rate", "undertriage", "undertriage_avoidable", "violations", "overtriage",
                                                "req_coverage", "excess_min", "cost", "ms_mean", "mcnemar_p_vs_cedcs"], csvrows)
    cal = [[load, lvl, v["n"], pci(v["appropriate"], v["ci"])] for load, d in e1.items() for lvl, v in d["calibration"].items()]
    md.append("### CEDCS confidence calibration (share of recommendations truly appropriate, by the confidence level CEDCS stated)\n\n" + table(["Load", "Stated confidence", "n", "Truly appropriate"], cal) + "\n")
    byp = [[load, SHORT[k]] + [pct(v[p]) for p in ("LOW", "MODERATE", "HIGH", "CRITICAL")] for load, d in e1.items() for k, v in d["undertriage_by_priority"].items()]
    md.append("### Undertriage by case urgency\n\n" + table(["Load", "Policy", "LOW", "MODERATE", "HIGH", "CRITICAL"], byp) + "\n")
    prov = [[load, num(d["n_eligible_mean"], 1), num(d["n_provisional_mean"], 1), str(d["rungs"])] for load, d in e1.items()]
    md.append("### CEDCS eligible set per case\n\n" + table(["Load", "Mean eligible", "Mean provisional", "Radius rung counts"], prov) + "\n")

    fig, axes = plt.subplots(1, len(e1), figsize=(4.2 * len(e1), 3.6), sharey=True)
    for ax, (load, d) in zip(axes if len(e1) > 1 else [axes], e1.items()):
        names = [n for n in d["summary"] if n != "oracle"]
        vals = [100 * d["summary"][n]["undertriage"] for n in names]
        errs = [[max(0.0, 100 * (d["summary"][n]["undertriage"] - d["summary"][n]["undertriage_ci"][0])) for n in names],
                [max(0.0, 100 * (d["summary"][n]["undertriage_ci"][1] - d["summary"][n]["undertriage"])) for n in names]]
        ax.bar([SHORT[n] for n in names], vals, yerr=errs, color=[OKABE[SHORT[n]] for n in names], capsize=3)
        _style(ax, f"City load: {load}", "Undertriage (%)")
    fig.suptitle("E1: recommendations missing a REQUIRED capability (lower is better)", fontsize=11, x=0.01, ha="left")
    fig.tight_layout()
    fig.savefig(fig_dir / "e1_undertriage.png", dpi=200)
    plt.close(fig)

    # ------------------------------------------------------------ B5
    if res.get("b5") and res["b5"].get("B5"):
        b = res["b5"]
        rows = [["B5 LLM chooses, no gate", pci(b["B5"]["undertriage"], b["B5"]["undertriage_ci"]), f"{b['B5']['violations']} ({pct(b['B5']['violation_rate'])})", pct(b["B5"]["overtriage"]), num(b["B5"]["req_coverage"][0], 3)]]
        for k, s in b["same_cases"].items():
            rows.append([SHORT[k], pci(s["undertriage"], s["undertriage_ci"]), f"{s['violations']} ({pct(s['violation_rate'])})", pct(s["overtriage"]), num(s["req_coverage"][0], 3)])
        md.append(f"## E1b. B5: a language model picks the hospital with no eligibility gate (subset of {b['n']} cases, {b['errors']} unusable answers)\n\n"
                  + table(["Policy", "Undertriage", "Safety violations", "Overtriage", "Required-capability coverage"], rows) + "\n")

    # ------------------------------------------------------------ E2
    e2 = res["e2"]
    rows, csvrows = [], []
    for age, d in e2.items():
        for name, s in d["summary"].items():
            rows.append([age, name.replace(" soft ranking, no gate, no freshness", ""), pci(s["undertriage"], s["undertriage_ci"]), pct(s["handoff_rate"]), num(s["req_coverage"][0], 3)])
            csvrows.append([age, name, s["undertriage"], s["handoff_rate"], s["req_coverage"][0]])
    md.append("## E2. Freshness ablation: undertriage as reported data ages\n\n" + table(["Data age (h)", "Policy", "Undertriage", "Handoff", "Coverage"], rows)
              + "\n\n" + table(["Data age (h)", "McNemar p (freshness on vs off)", "HIGH-confidence correct (on)", "HIGH-confidence correct (off)"],
                               [[a, pval(d["mcnemar_p_on_vs_off"]), pci(d["calibration_on"]["HIGH"]["appropriate"], d["calibration_on"]["HIGH"]["ci"]) + f" (n={d['calibration_on']['HIGH']['n']})",
                                 pci(d["calibration_off"]["HIGH"]["appropriate"], d["calibration_off"]["HIGH"]["ci"]) + f" (n={d['calibration_off']['HIGH']['n']})"] for a, d in e2.items()]) + "\n")
    write_csv(out / "e2_freshness.csv", ["age_h", "policy", "undertriage", "handoff_rate", "req_coverage"], csvrows)
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    ages = list(e2)
    for name, col in (("CEDCS (freshness on)", OKABE["CEDCS"]), ("CEDCS (freshness off)", OKABE["B4"]), ("B4 soft ranking, no gate, no freshness", OKABE["B3"])):
        ax.plot([float(a) for a in ages], [100 * e2[a]["summary"][name]["undertriage"] for a in ages], marker="o", label=name.replace(" soft ranking, no gate, no freshness", ""), color=col)
    ax.set_xlabel("Age of reported data (hours)")
    _style(ax, "E2: effect of data staleness", "Undertriage (%)")
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / "e2_freshness.png", dpi=200)
    plt.close(fig)

    # ------------------------------------------------------------ E3
    e3 = res["e3"]
    rows, csvrows = [], []
    for p, d in e3.items():
        for name, s in d["summary"].items():
            v = d["violations_of_given_profile"].get(name)
            rows.append([p, SHORT[name], pct(d["undertriage_when_corrupted"][name]), pct(s["undertriage"]), "-" if v is None else f"{v['count']} / {v['of']}"])
            csvrows.append([p, SHORT[name], d["undertriage_when_corrupted"][name], s["undertriage"], None if v is None else v["count"], None if v is None else v["of"]])
    md.append("## E3. Safety stress test: wrong triage injected (a REQUIRED capability dropped and priority lowered by one level)\n\n"
              + table(["Share of cases with wrong triage", "Policy", "Undertriage on the corrupted cases", "Undertriage overall", "Violations of the profile it was GIVEN"], rows) + "\n")
    write_csv(out / "e3_safety.csv", ["p_error", "policy", "undertriage_corrupted", "undertriage_all", "violations_given", "issued"], csvrows)
    fig, ax = plt.subplots(figsize=(5.2, 3.6))
    ps = list(e3)
    for name in ("B3 distance + specialty", "B4 soft ranking, no gate, no freshness", "CEDCS"):
        ax.plot([100 * float(p) for p in ps], [100 * e3[p]["summary"][name]["undertriage"] for p in ps], marker="o", label=SHORT[name], color=OKABE[SHORT[name]])
    ax.set_xlabel("Cases with wrong triage (%)")
    _style(ax, "E3: undertriage as triage errors increase", "Undertriage vs ground truth (%)")
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / "e3_safety.png", dpi=200)
    plt.close(fig)

    # ------------------------------------------------------------ E4
    e4 = res["e4"]
    rows = [[lvl, num(d["required_recall_mean"], 3), pct(d["priority_underestimated"]), pci(d["summary"]["undertriage"], d["summary"]["undertriage_ci"]), pct(d["summary"]["handoff_rate"])] for lvl, d in e4.items()]
    md.append("## E4. Input-noise robustness (rule-based triage of a degraded text; the language-model triage is not part of this table)\n\n"
              + table(["Noise level", "Mean recall of true REQUIRED set", "Priority underestimated", "Undertriage", "Handoff"], rows)
              + "\n\nNoise levels: 0 clean; 1 one clause lost; 2 additionally a 35 % chance of a wrong complaint; 3 additionally cut-off, shouted, panic text.\n")
    write_csv(out / "e4_noise.csv", ["level", "required_recall", "priority_underestimated", "undertriage", "handoff_rate"],
              [[l, d["required_recall_mean"], d["priority_underestimated"], d["summary"]["undertriage"], d["summary"]["handoff_rate"]] for l, d in e4.items()])

    if res.get("e4_llm"):
        rows = []
        for lvl, d in res["e4_llm"].items():
            for lab, k in (("AI agents (Groq / NVIDIA)", "ai"), ("rule-based triage", "rules_same_cases")):
                s = d[k]["summary"]
                rows.append([lvl, lab, f"{d['n']} of {d['n'] + d['errors']}", num(d[k]["recall"], 3), pct(d[k]["priority_underestimated"]), pci(s["undertriage"], s["undertriage_ci"])])
        md.append("### E4b. The same degraded texts triaged by the real AI agents (subset) next to the rule-based triage on exactly the same cases\n\n"
                  + table(["Noise level", "Triage", "Cases completed of attempted", "Mean recall of true REQUIRED set", "Priority underestimated", "Undertriage"], rows) + "\n")

    # ------------------------------------------------------------ E5
    e5 = res["e5"]
    md.append("## E5. Weight sensitivity\n\n" + table(["Measure", "Value"], [
        ["Baseline undertriage (Table 1 weights)", pct(e5["baseline_undertriage"])],
        [f"Undertriage over {e5['draws']} random weight vectors (each component x U(1-{e5['spread']}, 1+{e5['spread']}))",
         f"min {pct(e5['undertriage_min'])}, mean {pct(e5['undertriage_mean'])}, max {pct(e5['undertriage_max'])}"],
        ["Same top choice as the baseline weights", f"min {pct(e5['top1_agreement_min'])}, mean {pct(e5['top1_agreement_mean'])}, max {pct(e5['top1_agreement_max'])}"]]) + "\n")
    write_csv(out / "e5_weights.csv", ["draw", "undertriage", "top1_agreement", "excess_min"], [[i, r["undertriage"], r["top1_agreement"], r["excess_min"]] for i, r in enumerate(e5["per_draw"])])

    # ------------------------------------------------------------ E6
    e6 = res["e6"]
    rows = [[q, pct(d["avoidable_share"]), pct(d["widened_rate"]), pct(d["handoff_rate"]), pct(d["handoff_when_avoidable"]), pct(d["handoff_when_unavoidable"]), pct(d["undertriage"]), d["violations"]] for q, d in e6.items()]
    md.append("## E6. Escalation behaviour as supply is removed\n\n" + table(["Share of key capabilities removed per hospital", "Cases where a truly appropriate hospital exists", "Radius widened to 25 km",
                                                                              "Operator handoff", "Handoff when an appropriate hospital existed", "Handoff when none existed", "Undertriage of issued recommendations",
                                                                              "Safety violations"], rows) + "\n")
    write_csv(out / "e6_escalation.csv", ["q", "avoidable_share", "widened_rate", "handoff_rate", "handoff_when_avoidable", "handoff_when_unavoidable", "undertriage", "violations"],
              [[q, d["avoidable_share"], d["widened_rate"], d["handoff_rate"], d["handoff_when_avoidable"], d["handoff_when_unavoidable"], d["undertriage"], d["violations"]] for q, d in e6.items()])
    fig, ax = plt.subplots(figsize=(5.4, 3.6))
    qs = list(e6)
    for key, lab, col in (("widened_rate", "radius widened", OKABE["B2"]), ("handoff_rate", "operator handoff", OKABE["B5"]), ("undertriage", "undertriage of issued", OKABE["CEDCS"])):
        ax.plot([100 * float(q) for q in qs], [100 * e6[q][key] for q in qs], marker="o", label=lab, color=col)
    ax.set_xlabel("Key capabilities removed from each hospital (%)")
    _style(ax, "E6: behaviour as supply shrinks", "Share of cases (%)")
    ax.legend(frameon=False, fontsize=8)
    fig.tight_layout()
    fig.savefig(fig_dir / "e6_escalation.png", dpi=200)
    plt.close(fig)

    # ------------------------------------------------------------ latency
    lc = res["latency_core"]
    md.append("## Latency\n\nDeterministic decision core alone (freshness scoring, eligibility gate, ranking, confidence), wall-clock per case, "
              f"n={lc['n']}: mean {num(lc['mean_ms'], 2)} ms, median {num(lc['p50_ms'], 2)} ms, p95 {num(lc['p95_ms'], 2)} ms, max {num(lc['max_ms'], 2)} ms.\n")
    real = res.get("latency_real")
    if real and real.get("latency", {}).get("total"):
        t = real["latency"]["total"]
        rows = [["Whole pipeline", t["n"], num(t["p50"] / 1000), num(t["p95"] / 1000), num(t["max"] / 1000)]]
        for s in real["latency"]["stages"]:
            if s["depth"] >= 1:
                rows.append([("  " * (s["depth"] - 1)) + s["stage"].replace("_", " ").lower(), s["n"], num(s["p50"] / 1000, 3), num(s["p95"] / 1000, 3), num(s["max"] / 1000, 3)])
        md.append("### Measured latency of the full live pipeline (real runs saved in the history: language models, maps, hospital search)\n\n"
                  + table(["Stage", "n", "median (s)", "p95 (s)", "max (s)"], rows) + "\n")
        write_csv(out / "latency_real_stages.csv", ["stage", "depth", "n", "mean_ms", "p50_ms", "p95_ms", "max_ms"],
                  [[s["stage"], s["depth"], s["n"], s["mean"], s["p50"], s["p95"], s["max"]] for s in real["latency"]["stages"]])
        phases = [s for s in real["latency"]["stages"] if s["depth"] == 1]
        if phases:
            fig, ax = plt.subplots(figsize=(5.6, 3.2))
            ax.barh([s["stage"].replace("_", " ").lower() for s in phases], [s["p50"] / 1000 for s in phases], color=OKABE["CEDCS"])
            ax.set_xlabel("Median seconds")
            ax.invert_yaxis()
            _style(ax, "Where the time goes (pipeline phases)", "")
            fig.tight_layout()
            fig.savefig(fig_dir / "latency_phases.png", dpi=200)
            plt.close(fig)
    return "\n".join(md)
